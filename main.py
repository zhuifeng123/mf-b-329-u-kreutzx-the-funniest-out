#!/usr/bin/env python3
import os

ENTRY = "Out of office. My auto-reply has more job security than I do."


def main() -> None:
    os.makedirs("/output", exist_ok=True)
    with open("/output/entry.txt", "w", encoding="utf-8", newline="\n") as f:
        f.write(ENTRY + "\n")


if __name__ == "__main__":
    main()
